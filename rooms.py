NUMERATOR_MONDAY = date(2026, 8, 31)


def week_type(day):
    return ("Ч", "З")[((day - NUMERATOR_MONDAY).days // 7) % 2]


def minutes(clock):
    hour, minute = map(int, clock.split(":"))
    return hour * 60 + minute


class Building:
    @classmethod
    def status(cls, calendar, day, start, end):
        return {room.name: room.is_busy(calendar, day, start, end)
                for room in ROOMS.values() if room.building is cls}


class Room:
    parallel_classes = 1

    @classmethod
    def is_busy(cls, calendar, day, start, end):
        return any(calendar.busy(key, day, start, end) for key in cls.keys)


class RoomCalendar:
    def __init__(self, saved=()):
        self.by_date = defaultdict(set)
        self.by_week = defaultdict(set)
        self.shared_bookings = defaultdict(list)
        for room in ROOMS.values():
            for key in room.keys:
                for day, start, end in room.dated:
                    self.by_date[key, date.fromisoformat(day)].add((start, end))
                for weekday, parity, start, end in room.weekly:
                    self.by_week[key, weekday, parity].add((start, end))
        for key, day, start, end in saved:
            self._mark_key(key, date.fromisoformat(day), start, end, True)

    def busy(self, key, day, start, end):
        return self.free_count(key, day, start, end) == 0

    def free_count(self, key, day, start, end):
        intervals = self.by_date.get((key, day), ())
        if any(a < end and start < b for a,b in intervals):
            return 0
        if SEMESTER[0] <= day <= SEMESTER[1]:
            parity = week_type(day)
            if any(a < end and start < b for week in ("обе", parity)
                   for a,b in self.by_week.get((key, day.isoweekday(), week), ())):
                return 0
        capacity = SHARED_KEYS.get(key, 1)
        changes = []
        for a, b in self.shared_bookings.get((key, day), ()):
            if a < end and start < b:
                changes.extend(((max(a, start), 1), (min(b, end), -1)))
        active = peak = 0
        for _, delta in sorted(changes):
            active += delta
            peak = max(peak, active)
        return max(0, capacity - peak)

    def _mark_key(self, key, day, start, end, occupied):
        if key in SHARED_KEYS:
            intervals = self.shared_bookings[key, day]
            if occupied:
                intervals.append((start, end))
            else:
                intervals.remove((start, end))
        elif occupied:
            self.by_date[key, day].add((start, end))
        else:
            self.by_date[key, day].remove((start, end))

    def mark(self, room, day, start, end, occupied):
        if room == REMOTE:
            return
        for key in ROOMS[room].keys:
            self._mark_key(key, day, start, end, occupied)


@contextmanager
def booking_session(owner=None, first=None, last=None):
    """При пересчёте заменяем брони подразделения в периоде одним коммитом."""
    if owner is None and not DATABASE.exists():
        yield RoomCalendar(), None
        return
    db = sqlite3.connect(DATABASE, timeout=60)
    try:
        with db:
            if owner is not None:
                db.execute("BEGIN IMMEDIATE")
            db.execute("""CREATE TABLE IF NOT EXISTS booking
                       (owner TEXT, room_key TEXT, day TEXT, start INTEGER, end INTEGER)""")
            if owner is not None:
                db.execute("DELETE FROM booking WHERE owner=? AND day BETWEEN ? AND ?",
                           (owner, first, last))
            saved = db.execute("SELECT room_key, day, start, end FROM booking")
            yield RoomCalendar(saved), db
    finally:
        db.close()


def save_bookings(db, owner, lessons, starts, ends):
    rows = ((owner, key, lesson.slot.day.isoformat(), minutes(starts[lesson.slot.period-1]),
             minutes(ends[lesson.slot.period-1])) for lesson in lessons if lesson.room != REMOTE
            for key in ROOMS[lesson.room].keys)
    db.executemany("INSERT INTO booking VALUES (?,?,?,?,?)", rows)


class RoomAllocator:
    def __init__(self, calendar, starts, ends):
        self.calendar = calendar
        self.bells = list(zip(map(minutes, starts), map(minutes, ends)))

    def choices(self, options, count, allowed, daily_limit):
        candidates = {}
        for slot in options:
            start, end = self.bells[slot.period-1]
            rooms = [r for r in allowed if r == REMOTE or
                     not ROOMS[r].is_busy(self.calendar, slot.day, start, end)]
            if rooms:
                candidates[slot] = rooms
        for slots in combinations(candidates, count):
            if count > 1 and any(n > daily_limit[day] for day, n in Counter(s.day for s in slots).items()):
                continue
            for assignment in product(*(candidates[s] for s in slots)):
                yield tuple(zip(slots, assignment))

    def mark(self, assignment, occupied):
        for slot, room in assignment:
            start, end = self.bells[slot.period-1]
            self.calendar.mark(room, slot.day, start, end, occupied)


